def master_rows(regime=None):
    """③ 거장 비교표: each master's day, regime multipliers, cash floor, V1 replay and, given the regime, its 추천 등급 now."""
    import vibe_longterm as L
    rows = []
    for k, p in D.PROFILES.items():
        when = f"하락일 우선(최대 {p['wait']}일)" if p['when'] == 'dip' else '정한 주기마다'
        rows.append({'거장': p['label'], '관점': p['title'], '사는 날': when + (' · 급락일 1.5배' if p.get('crash') else ''),
                     **{L.REGIMES[r][0]: f"{p['mult'][r]:g}" for r in D.REGIMES}, '현금 하한(여운봉 계좌)': f"{p['floor']:.0%}",
                     '재현 V1': p['evidence'], '지금 국면 등급': ' — '.join(D.profile_grade(k, regime)) if regime else '—'})
    return rows


